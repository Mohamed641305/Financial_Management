/** Arabic month names — index 1–12 */
const MONTH_NAMES = [
  '',
  'يناير',  'فبراير', 'مارس',   'أبريل',
  'مايو',   'يونيو',  'يوليو',  'أغسطس',
  'سبتمبر', 'أكتوبر', 'نوفمبر', 'ديسمبر',
];

/** English 3-letter abbreviations — index 1–12 */
const MONTH_EN = [
  '',
  'Jan', 'Feb', 'Mar', 'Apr',
  'May', 'Jun', 'Jul', 'Aug',
  'Sep', 'Oct', 'Nov', 'Dec',
];

/**
 * Returns combined header label:
 *   يناير
 *   (Jan)
 */
function monthLabel(m) {
  return `${MONTH_NAMES[m]}\n(${MONTH_EN[m]})`;
}

